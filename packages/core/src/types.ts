import { parseSchema, type Column, type Table } from "./parse.js";
import { topLevel } from "./plan.js";
import { unquote } from "./tokenize.js";

export interface TypesOptions {
  /** Emit Standard Schema validators, with the row types inferred from them. */
  standardSchema?: boolean;
}

type Affinity = "integer" | "real" | "text" | "blob" | "any";

interface Field {
  name: string;
  affinity: Affinity;
  literals?: (string | number)[];
  nullable: boolean;
}

// Words that end a column's declared type and start its constraints.
const TYPE_END = new Set([
  "constraint",
  "primary",
  "not",
  "null",
  "unique",
  "check",
  "default",
  "collate",
  "references",
  "generated",
  "as",
]);

/** TypeScript row types (or Standard Schema validators) for every table in a schema. */
export function generateTypes(sql: string, options: TypesOptions = {}): string {
  const tables = [...parseSchema(sql).tables.values()];
  const header = "// Generated by dodai from the schema. Do not edit.\n";
  if (options.standardSchema) {
    const imports = 'import { defineRow, type InferRow } from "@dodaijs/core";\n';
    return `${header}${imports}\n${tables.map(rowSchema).join("\n")}`;
  }
  return `${header}\n${tables.map(typeAlias).join("\n")}`;
}

function typeAlias(table: Table): string {
  const fields = fieldsOf(table).map((f) => {
    const base = f.literals
      ? f.literals.map((l) => JSON.stringify(l)).join(" | ")
      : { integer: "number", real: "number", text: "string", blob: "ArrayBuffer", any: "unknown" }[
          f.affinity
        ];
    const type = f.nullable && f.affinity !== "any" ? `${base} | null` : base;
    return `  ${property(f.name)}: ${type};\n`;
  });
  return `export type ${rowName(table)} = {\n${fields.join("")}};\n`;
}

function rowSchema(table: Table): string {
  const name = rowName(table);
  const columns = fieldsOf(table).map((f) => {
    const spec = [`type: "${f.affinity}"`];
    if (f.literals) spec.push(`values: [${f.literals.map((l) => JSON.stringify(l)).join(", ")}]`);
    if (f.nullable && f.affinity !== "any") spec.push("nullable: true");
    return `  ${property(f.name)}: { ${spec.join(", ")} },\n`;
  });
  return `export const ${name} = defineRow(${JSON.stringify(table.name)}, {\n${columns.join("")}});\nexport type ${name} = InferRow<typeof ${name}>;\n`;
}

function fieldsOf(table: Table): Field[] {
  const primaryKey = primaryKeyColumns(table);
  const withoutRowid = table.options.includes("rowid");
  return table.columns.map((column) => {
    const type = declaredType(column);
    const inPrimaryKey = primaryKey.includes(column.key);
    // Only an INTEGER PRIMARY KEY (the rowid) or a WITHOUT ROWID primary key
    // rejects NULL without saying so; SQLite lets other key columns hold NULL.
    const implicitNotNull =
      inPrimaryKey && (withoutRowid || (type === "integer" && primaryKey.length === 1));
    return {
      name: column.name,
      affinity: affinity(type),
      literals: checkLiterals(column, table),
      nullable: !implicitNotNull && !hasNotNull(column.def),
    };
  });
}

export function declaredType(column: Column): string {
  const words: string[] = [];
  for (const t of column.def) {
    if (TYPE_END.has(t)) break;
    words.push(t);
  }
  return words.join(" ");
}

// SQLite's column affinity rules, https://www.sqlite.org/datatype3.html#determination_of_column_affinity
function affinity(type: string): Affinity {
  if (type === "" || type === "any") return "any";
  if (type.includes("int")) return "integer";
  if (/char|clob|text/.test(type)) return "text";
  if (type.includes("blob")) return "blob";
  // REAL and NUMERIC affinity both read back as numbers.
  return "real";
}

export function hasNotNull(def: string[]): boolean {
  const top = topLevel(def);
  return top.some((t, k) => t === "not" && top[k + 1] === "null");
}

export function primaryKeyColumns(table: Table): string[] {
  const inline = table.columns.filter((c) => topLevel(c.def).includes("primary")).map((c) => c.key);
  const keys = table.columns.map((c) => c.key);
  const constraint = table.constraints.find((c) => c.includes("primary"));
  if (!constraint) return inline;
  return constraint.slice(constraint.indexOf("(")).filter((t) => keys.includes(t));
}

// `CHECK (col IN ('a', 'b'))`, on the column or the table, narrows the column
// to those literals.
function checkLiterals(column: Column, table: Table): (string | number)[] | undefined {
  for (const tokens of [column.def, ...table.constraints]) {
    for (let k = 0; k < tokens.length; k++) {
      if (tokens[k] !== "check" || tokens[k + 1] !== "(" || tokens[k + 2] !== column.key) continue;
      if (tokens[k + 3] !== "in" || tokens[k + 4] !== "(") continue;
      const literals: (string | number)[] = [];
      for (let j = k + 5; j < tokens.length; j += 2) {
        const t = tokens[j]!;
        if (t.startsWith("'")) literals.push(unquote(t));
        else if (/^-?\d+(\.\d+)?$/.test(t)) literals.push(Number(t));
        else break;
        if (tokens[j + 1] === ")") return literals;
        if (tokens[j + 1] !== ",") break;
      }
    }
  }
  return undefined;
}

function rowName(table: Table): string {
  const pascal = table.name
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((part) => part[0]!.toUpperCase() + part.slice(1))
    .join("");
  return `${/^[0-9]/.test(pascal) ? "T" : ""}${pascal}Row`;
}

function property(name: string): string {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name);
}

import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { describe, expect, expectTypeOf, it } from "vitest";
import { defineRow, generateTypes, type InferRow, type StandardSchemaV1 } from "../src/index.js";
import { database, rows, sql } from "./helpers.js";

describe("row types generated from the schema", () => {
  it("follows SQLite's affinity rules and NOT NULL for column types", () => {
    const output = generateTypes(sql`
      CREATE TABLE profiles (
        id INTEGER PRIMARY KEY,
        handle VARCHAR(39) NOT NULL,
        score REAL,
        verified BOOLEAN NOT NULL DEFAULT 0,
        avatar BLOB,
        extra
      );
    `);

    expect(output.trimEnd()).toBe(sql`
      // Generated by dodai from the schema. Do not edit.

      export type ProfilesRow = {
        id: number;
        handle: string;
        score: number | null;
        verified: number;
        avatar: ArrayBuffer | null;
        extra: unknown;
      };
    `);
  });

  it("narrows a column to the values a CHECK lists", () => {
    const output = generateTypes(sql`
      CREATE TABLE devices (
        id TEXT NOT NULL,
        platform TEXT NOT NULL CHECK (platform IN ('ios','android','web')),
        tier INTEGER,
        CHECK (tier IN (1, 2))
      );
    `);

    expect(output.trimEnd()).toBe(sql`
      // Generated by dodai from the schema. Do not edit.

      export type DevicesRow = {
        id: string;
        platform: "ios" | "android" | "web";
        tier: 1 | 2 | null;
      };
    `);
  });

  it("makes primary key columns non-null only where SQLite enforces it", () => {
    const output = generateTypes(sql`
      CREATE TABLE legacy_keys (code TEXT PRIMARY KEY);
      CREATE TABLE strict_keys (code TEXT PRIMARY KEY) WITHOUT ROWID;
      CREATE TABLE memberships (
        group_id TEXT,
        user_id TEXT,
        PRIMARY KEY (group_id, user_id)
      ) WITHOUT ROWID;
    `);

    expect(output.trimEnd()).toBe(sql`
      // Generated by dodai from the schema. Do not edit.

      export type LegacyKeysRow = {
        code: string | null;
      };

      export type StrictKeysRow = {
        code: string;
      };

      export type MembershipsRow = {
        group_id: string;
        user_id: string;
      };
    `);
  });

  it("emits Standard Schema validators that accept the rows SQLite returns", async () => {
    const schema = sql`
      CREATE TABLE devices (
        id INTEGER PRIMARY KEY,
        platform TEXT NOT NULL CHECK (platform IN ('ios','android')),
        label TEXT,
        weight REAL NOT NULL DEFAULT 1.5
      );
    `;

    const output = generateTypes(schema, { standardSchema: true });

    expect(output.trimEnd()).toBe(sql`
      // Generated by dodai from the schema. Do not edit.
      import { defineRow, type InferRow } from "@dodaijs/core";

      export const DevicesRow = defineRow("devices", {
        id: { type: "integer" },
        platform: { type: "text", values: ["ios", "android"] },
        label: { type: "text", nullable: true },
        weight: { type: "real" },
      });
      export type DevicesRow = InferRow<typeof DevicesRow>;
    `);

    // Point the generated import at this checkout instead of the published package.
    const dir = mkdtempSync(join(import.meta.dirname, ".generated-"));
    const file = join(dir, "schema.gen.ts");
    const core = pathToFileURL(join(import.meta.dirname, "../src/index.ts")).href;
    writeFileSync(file, output.replace('"@dodaijs/core"', JSON.stringify(core)));
    const { DevicesRow } = (await import(pathToFileURL(file).href).finally(() =>
      rmSync(dir, { recursive: true }),
    )) as { DevicesRow: StandardSchemaV1 };
    const db = database(
      schema,
      "INSERT INTO devices (id, platform, label) VALUES (1, 'ios', NULL), (2, 'android', 'tablet')",
    );
    for (const row of rows(db, "SELECT * FROM devices")) {
      expect(await DevicesRow["~standard"].validate(row)).toEqual({ value: row });
    }
  });
});

describe("defineRow", () => {
  const Devices = defineRow("devices", {
    id: { type: "integer" },
    platform: { type: "text", values: ["ios", "android"] },
    label: { type: "text", nullable: true },
    data: { type: "blob", nullable: true },
    extra: { type: "any" },
  });

  it("infers the row type from the columns", () => {
    expectTypeOf<InferRow<typeof Devices>>().toEqualTypeOf<{
      id: number;
      platform: "ios" | "android";
      label: string | null;
      data: ArrayBuffer | null;
      extra: unknown;
    }>();
  });

  it("accepts a row that matches every column", () => {
    const row = { id: 1, platform: "ios", label: null, data: new ArrayBuffer(1), extra: "x" };

    expect(Devices["~standard"].validate(row)).toEqual({ value: row });
  });

  it("reports each column that does not match, with its path", () => {
    const result = Devices["~standard"].validate({
      id: 1.5,
      platform: "web",
      label: 3,
      extra: null,
    });

    expect(result).toEqual({
      issues: [
        { message: "expected integer", path: ["id"] },
        { message: 'expected one of ["ios","android"]', path: ["platform"] },
        { message: "expected text or null", path: ["label"] },
        { message: "missing column", path: ["data"] },
      ],
    });
  });

  it("rejects a value that is not a row", () => {
    expect(Devices["~standard"].validate(null)).toEqual({
      issues: [{ message: "expected a devices row" }],
    });
  });
});
